#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "..");
const CLI_DIR = path.join(REPO_ROOT, "packages", "cli");
const KERNEL_PUBLIC_DIR = path.join(REPO_ROOT, "packages", "kernel", "public");
const CLI_PKG_PATH = path.join(CLI_DIR, "package.json");
const DESKTOP_BINARIES_DIR = path.join(REPO_ROOT, "apps", "desktop", "src-tauri", "binaries");
const DESKTOP_TARGET_DIR = path.join(REPO_ROOT, "apps", "desktop", "src-tauri", "target");

const GENERATED_ASSETS_PATH = path.join(CLI_DIR, "src", "embedded-public.generated.ts");
const GENERATED_ENTRY_PATH = path.join(CLI_DIR, ".bin-compiled.generated.ts");

const TARGET_SPECS = {
  "darwin-arm64": {
    bunTarget: "bun-darwin-arm64",
    rustTriple: "aarch64-apple-darwin",
    ext: "",
  },
  "darwin-x64": {
    bunTarget: "bun-darwin-x64",
    rustTriple: "x86_64-apple-darwin",
    ext: "",
  },
  "windows-x64": {
    bunTarget: "bun-windows-x64",
    rustTriple: "x86_64-pc-windows-msvc",
    ext: ".exe",
  },
  "linux-x64": {
    bunTarget: "bun-linux-x64",
    rustTriple: "x86_64-unknown-linux-gnu",
    ext: "",
  },
};

const ALL_TARGET_NAMES = Object.keys(TARGET_SPECS);

function printUsage() {
  process.stdout.write(
    [
      "Kiln Standalone Binary Builder (Bun --compile)",
      "",
      "Usage:",
      "  node scripts/build-binary.mjs [options]",
      "",
      "Options:",
      "  --target <name>   host | darwin-arm64 | darwin-x64 | windows-x64 | linux-x64 | all (default: host)",
      "  --out-dir <dir>   Output directory (default: release-artifacts/bin)",
      "  --stage-sidecar   Copy compiled binary to apps/desktop/src-tauri/binaries/kiln-<triple>(.exe)",
      "  --bytecode        Enable Bun --bytecode precompilation (opt-in)",
      "  --version <ver>   Override version tag in output filename (default: packages/cli/package.json)",
      "  -h, --help        Show this help message",
      "",
    ].join("\n"),
  );
}

function resolveHostTarget() {
  const key = `${process.platform}-${process.arch}`;
  switch (key) {
    case "darwin-arm64":
      return "darwin-arm64";
    case "darwin-x64":
      return "darwin-x64";
    case "win32-x64":
      return "windows-x64";
    case "linux-x64":
      return "linux-x64";
    default:
      throw new Error(
        `Unsupported host platform/arch "${key}". Specify --target (${ALL_TARGET_NAMES.join("|")}).`,
      );
  }
}

function collectPublicFiles(rootDir) {
  const canonicalRoot = fs.realpathSync(rootDir);
  const results = [];

  function walk(currentDir, relPrefix) {
    const entries = fs
      .readdirSync(currentDir, { withFileTypes: true })
      .sort((a, b) => a.name.localeCompare(b.name));

    for (const entry of entries) {
      if (entry.name.startsWith(".")) {
        continue;
      }
      const absPath = path.join(currentDir, entry.name);
      const canonical = fs.realpathSync(absPath);
      const prefixWithSep = canonicalRoot.endsWith(path.sep)
        ? canonicalRoot
        : `${canonicalRoot}${path.sep}`;
      if (canonical !== canonicalRoot && !canonical.startsWith(prefixWithSep)) {
        throw new Error(`Refusing symlink escaping public dir: ${absPath}`);
      }

      const relPosix = relPrefix ? `${relPrefix}/${entry.name}` : entry.name;
      if (entry.isDirectory()) {
        walk(absPath, relPosix);
      } else if (entry.isFile()) {
        results.push({ relPosix, absPath: canonical });
      }
    }
  }

  walk(canonicalRoot, "");
  return results;
}

function generateEmbeddedPublicModules(files) {
  const imports = [];
  const entries = [];

  files.forEach((file, idx) => {
    const varName = `asset_${idx}`;
    const relImport = path
      .relative(path.dirname(GENERATED_ASSETS_PATH), file.absPath)
      .split(path.sep)
      .join("/");
    const spec = relImport.startsWith(".") ? relImport : `./${relImport}`;
    imports.push(`import ${varName} from ${JSON.stringify(spec)} with { type: "file" };`);
    entries.push(`  [${JSON.stringify(file.relPosix)}, ${varName}],`);
  });

  const assetsModule = [
    "// Auto-generated by scripts/build-binary.mjs (gitignored; do not edit).",
    'import fs from "node:fs";',
    'import type { EmbeddedStaticAsset } from "@kiln/kernel";',
    'import { setEmbeddedPublicAssets } from "./embedded-public.js";',
    ...imports,
    "",
    "export function registerEmbeddedPublicAssets(): void {",
    "  const rawEntries: ReadonlyArray<readonly [string, string]> = [",
    ...entries,
    "  ];",
    "  const map = new Map<string, EmbeddedStaticAsset>();",
    "  for (const [relPosix, embeddedPath] of rawEntries) {",
    "    let cached: Uint8Array | null = null;",
    "    map.set(relPosix, {",
    "      readBytes(): Uint8Array {",
    "        if (cached === null) {",
    "          cached = new Uint8Array(fs.readFileSync(embeddedPath));",
    "        }",
    "        return cached;",
    "      },",
    "    });",
    "  }",
    "  setEmbeddedPublicAssets(map);",
    "}",
    "",
  ].join("\n");

  const entryModule = [
    "// Auto-generated by scripts/build-binary.mjs (gitignored; do not edit).",
    'import { registerEmbeddedPublicAssets } from "./src/embedded-public.generated.ts";',
    'import { runCliProcessMain } from "./src/commands.ts";',
    "",
    "registerEmbeddedPublicAssets();",
    "runCliProcessMain();",
    "",
  ].join("\n");

  fs.writeFileSync(GENERATED_ASSETS_PATH, assetsModule, "utf8");
  fs.writeFileSync(GENERATED_ENTRY_PATH, entryModule, "utf8");
}

function cleanupGeneratedModules() {
  fs.rmSync(GENERATED_ASSETS_PATH, { force: true });
  fs.rmSync(GENERATED_ENTRY_PATH, { force: true });
}

function sha256File(filePath) {
  const hash = crypto.createHash("sha256");
  hash.update(fs.readFileSync(filePath));
  return hash.digest("hex");
}

function removeStaleTauriSidecarCopies(ext) {
  // Guard against stale stripped sidecar copies cached inside target/{debug,release}/
  for (const profile of ["debug", "release"]) {
    const stale = path.join(DESKTOP_TARGET_DIR, profile, `kiln${ext}`);
    fs.rmSync(stale, { force: true });
  }
}

function main() {
  const parsed = parseArgs({
    args: process.argv.slice(2),
    options: {
      target: { type: "string", default: "host" },
      "out-dir": { type: "string", default: path.join("release-artifacts", "bin") },
      "stage-sidecar": { type: "boolean", default: false },
      bytecode: { type: "boolean", default: false },
      version: { type: "string" },
      help: { type: "boolean", short: "h", default: false },
    },
    strict: true,
    allowPositionals: false,
  });

  if (parsed.values.help) {
    printUsage();
    return;
  }

  const cliPkg = JSON.parse(fs.readFileSync(CLI_PKG_PATH, "utf8"));
  const version = (parsed.values.version ?? cliPkg.version ?? "").replace(/^v/, "").trim();
  if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
    throw new Error(`Invalid release version "${version}"`);
  }

  const indexHtmlPath = path.join(KERNEL_PUBLIC_DIR, "index.html");
  if (!fs.existsSync(indexHtmlPath)) {
    throw new Error(
      `Missing Web UI build at ${indexHtmlPath}. Run "pnpm build" before building standalone binaries.`,
    );
  }

  const rawTarget = parsed.values.target;
  const targets =
    rawTarget === "all"
      ? ALL_TARGET_NAMES
      : rawTarget === "host"
        ? [resolveHostTarget()]
        : [rawTarget];

  for (const t of targets) {
    if (!(t in TARGET_SPECS)) {
      throw new Error(
        `Unknown --target "${t}". Expected host, all, or one of: ${ALL_TARGET_NAMES.join(", ")}`,
      );
    }
  }

  const bunCheck = spawnSync("bun", ["--version"], { encoding: "utf8" });
  if (bunCheck.error || bunCheck.status !== 0) {
    throw new Error(
      `Bun executable is required to compile standalone binaries (${bunCheck.error?.message ?? bunCheck.stderr?.trim() ?? "not found"}).`,
    );
  }
  const bunVersion = bunCheck.stdout.trim();

  const outDir = path.resolve(REPO_ROOT, parsed.values["out-dir"]);
  fs.mkdirSync(outDir, { recursive: true });
  if (parsed.values["stage-sidecar"]) {
    fs.mkdirSync(DESKTOP_BINARIES_DIR, { recursive: true });
  }

  const publicFiles = collectPublicFiles(KERNEL_PUBLIC_DIR);
  if (publicFiles.length === 0) {
    throw new Error(`No files found under ${KERNEL_PUBLIC_DIR}. Run "pnpm build" first.`);
  }

  process.stdout.write(
    `Building Kiln v${version} standalone binary with Bun ${bunVersion} (${publicFiles.length} embedded public asset(s))...\n`,
  );

  try {
    generateEmbeddedPublicModules(publicFiles);

    for (const targetName of targets) {
      const spec = TARGET_SPECS[targetName];
      const artifactName = `kiln-v${version}-${targetName}${spec.ext}`;
      const outPath = path.join(outDir, artifactName);

      const bunArgs = [
        "build",
        "--compile",
        ...(parsed.values.bytecode ? ["--bytecode"] : []),
        `--target=${spec.bunTarget}`,
        "--outfile",
        outPath,
        GENERATED_ENTRY_PATH,
      ];

      process.stdout.write(`\n[build-binary] ${targetName} -> ${path.relative(REPO_ROOT, outPath)}\n`);
      const res = spawnSync("bun", bunArgs, {
        cwd: REPO_ROOT,
        stdio: "inherit",
      });
      if (res.error) {
        throw res.error;
      }
      if (res.status !== 0) {
        throw new Error(`bun build --compile failed for ${targetName} (exit ${res.status})`);
      }

      if (spec.ext === "" && process.platform !== "win32") {
        fs.chmodSync(outPath, 0o755);
      }

      const stat = fs.statSync(outPath);
      const digest = sha256File(outPath);
      const sizeMiB = (stat.size / (1024 * 1024)).toFixed(2);
      process.stdout.write(
        `[build-binary] Built ${artifactName}: ${stat.size} bytes (${sizeMiB} MiB), sha256=${digest}\n`,
      );

      if (parsed.values["stage-sidecar"]) {
        const sidecarName = `kiln-${spec.rustTriple}${spec.ext}`;
        const sidecarPath = path.join(DESKTOP_BINARIES_DIR, sidecarName);
        fs.copyFileSync(outPath, sidecarPath);
        if (spec.ext === "" && process.platform !== "win32") {
          fs.chmodSync(sidecarPath, 0o755);
        }
        removeStaleTauriSidecarCopies(spec.ext);
        process.stdout.write(
          `[build-binary] Staged Tauri sidecar: ${path.relative(REPO_ROOT, sidecarPath)}\n`,
        );
      }
    }
  } finally {
    cleanupGeneratedModules();
  }
}

try {
  main();
} catch (err) {
  const message = err instanceof Error ? err.message : String(err);
  process.stderr.write(`Error: ${message}\n`);
  process.exit(1);
}
